package com.nexperia.qms.common.storage;

import com.nexperia.qms.common.exception.NotFoundException;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

/**
 * Attachment storage on the local filesystem, which is what a single-machine
 * Windows deployment needs. Files are written under
 * {@code <root>/yyyy/MM/} so one directory never accumulates tens of thousands of
 * entries.
 *
 * The stored key is always generated by this application, never taken from user
 * input, and {@link #resolve} still refuses any key that would escape the root.
 */
@Service
public class LocalFsStorage implements StorageService {

    private static final Logger log = LoggerFactory.getLogger(LocalFsStorage.class);

    private final Path root;

    public LocalFsStorage(@Value("${qms.storage.root}") String root) {
        this.root = Path.of(root).toAbsolutePath().normalize();
    }

    @Override
    public String store(InputStream data, String objectKey) {
        Path target = resolve(objectKey);
        try {
            Files.createDirectories(target.getParent());
            // Write to a temporary file first: a half-written attachment must never
            // be visible under its final name.
            Path temp = Files.createTempFile(target.getParent(), "upload-", ".part");
            try {
                Files.copy(data, temp, StandardCopyOption.REPLACE_EXISTING);
                Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING,
                        StandardCopyOption.ATOMIC_MOVE);
            } catch (IOException e) {
                Files.deleteIfExists(temp);
                throw e;
            }
            return objectKey;
        } catch (IOException e) {
            throw new IllegalStateException("附件写入失败：" + objectKey, e);
        }
    }

    @Override
    public Resource load(String objectKey) {
        Path path = resolve(objectKey);
        if (!Files.isReadable(path)) {
            throw new NotFoundException("附件文件不存在：" + objectKey);
        }
        return new FileSystemResource(path);
    }

    @Override
    public void delete(String objectKey) {
        try {
            Files.deleteIfExists(resolve(objectKey));
        } catch (IOException e) {
            // A missing file is not worth failing the business operation over, but
            // it does mean the row and the disk have diverged, so say so.
            log.warn("Could not delete attachment file {}", objectKey, e);
        }
    }

    @Override
    public boolean exists(String objectKey) {
        return Files.isReadable(resolve(objectKey));
    }

    /** Absolute path under the root, rejecting anything that would escape it. */
    private Path resolve(String objectKey) {
        if (objectKey == null || objectKey.isBlank()) {
            throw new IllegalArgumentException("附件路径为空");
        }
        Path candidate = root.resolve(objectKey).normalize();
        if (!candidate.startsWith(root)) {
            throw new IllegalArgumentException("附件路径非法：" + objectKey);
        }
        return candidate;
    }
}
