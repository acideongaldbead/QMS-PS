-- ===========================================================================
-- V21 系统公告正文改为富文本（需求 3.0 / PS-003）
-- ===========================================================================
-- content 自 V1 起就是 text NOT NULL，注释也写着「内容 | 富文本，支持附件」，
-- 但 V9 种的 3 条公告是纯文本。本迁移只做数据：把仍是纯文本的行包成 HTML 段落，
-- 使首页抽屉用 v-html 渲染时不会把整段挤成一行无结构文本。
--
-- 无需改 schema：列本来就是 text。净化（去 script / 事件属性 / javascript: 链接）
-- 在应用写入侧完成，迁移只负责把历史数据搬进富文本形状。
--
-- 幂等：只在 content 不以 '<' 开头时改写，重复执行不会二次包裹。
-- 转义顺序：先 & 再 < >，避免二次转义。
-- ===========================================================================

SET search_path TO qms, public;

UPDATE system_announcement
   SET content = '<p>'
                 || replace(replace(replace(content, '&', '&amp;'), '<', '&lt;'), '>', '&gt;')
                 || '</p>'
 WHERE content NOT LIKE '<%'
   AND btrim(content) <> '';
