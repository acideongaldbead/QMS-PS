-- ===========================================================================
-- V5 翻译配置表（追加迁移）
-- ===========================================================================
-- 需求 3.17 要求后台可维护中英文词条（「翻译配置」）。基线里没有落点表，
-- 前端 vue-i18n 的静态词条只作兜底，后台改这里即时生效。
-- ===========================================================================

SET search_path TO qms, public;

CREATE TABLE translation (
    translation_id  bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    locale          varchar(16)  NOT NULL,
    msg_key         varchar(128) NOT NULL,
    msg_value       text         NOT NULL,
    module_code     varchar(32),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      varchar(32),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      varchar(32),
    is_deleted      boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_translation PRIMARY KEY (translation_id),
    CONSTRAINT uq_translation_key UNIQUE (locale, msg_key)
);
COMMENT ON TABLE translation IS '翻译配置 | 后台可维护的中英文词条；前端与后端取词优先读本表，静态词条仅作兜底';
COMMENT ON COLUMN translation.translation_id IS '词条ID | 自增 | PK';
COMMENT ON COLUMN translation.locale IS '语言 | zh-CN / en-US';
COMMENT ON COLUMN translation.msg_key IS '词条键 | 如 nav.ledger、stage.D4 | UQ(locale,msg_key)';
COMMENT ON COLUMN translation.msg_value IS '词条值 | 展示文本';
COMMENT ON COLUMN translation.module_code IS '所属模块 | 便于按模块批量维护';
COMMENT ON COLUMN translation.created_at IS '审计：创建时间';
COMMENT ON COLUMN translation.created_by IS '审计：创建人（员工ID）';
COMMENT ON COLUMN translation.updated_at IS '审计：最后修改时间';
COMMENT ON COLUMN translation.updated_by IS '审计：最后修改人（员工ID）';
COMMENT ON COLUMN translation.is_deleted IS '审计：软删除标记';

CREATE INDEX idx_translation_locale ON translation (locale) WHERE is_deleted = false;

CREATE TRIGGER trg_translation_updated_at BEFORE UPDATE ON translation
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
