-- ===========================================================================
-- V2 本地账号体系（追加迁移；V1 基线冻结，不改动）
-- ===========================================================================
-- 基线里没有账号表：原设计走公司 SSO，用户即 employee。
-- 一期用本地账号 + JWT，因此补 user_account；OAuth2 落地时只需换 AuthProvider，
-- 业务代码不动（subject 始终是 employee_id）。
--
-- password_hash 说明：种子数据（V9）写入哨兵值 'CHANGE_ME'，应用在 local
-- profile 启动时用 BCrypt 重新计算并覆盖。这样仓库里不存任何口令散列。
-- ===========================================================================

SET search_path TO qms, public;

CREATE TABLE user_account (
    account_id        bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id       varchar(32)  NOT NULL,
    username          varchar(64)  NOT NULL,
    password_hash     varchar(100) NOT NULL,
    is_active         boolean      NOT NULL DEFAULT true,
    failed_attempts   integer      NOT NULL DEFAULT 0,
    locked_until      timestamptz,
    last_login_at     timestamptz,
    must_change_pwd   boolean      NOT NULL DEFAULT false,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    created_by        varchar(32),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    updated_by        varchar(32),
    is_deleted        boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_user_account PRIMARY KEY (account_id),
    CONSTRAINT uq_user_account_employee UNIQUE (employee_id),
    CONSTRAINT uq_user_account_username UNIQUE (username)
);
COMMENT ON TABLE user_account IS '登录账号 | 一期本地账号密码；与 employee 一对一。二期对接 SSO 后本表仅作映射保留';
COMMENT ON COLUMN user_account.account_id IS '账号ID | 自增 | PK';
COMMENT ON COLUMN user_account.employee_id IS '员工ID | 与 employee 一对一 | FK';
COMMENT ON COLUMN user_account.username IS '登录账号 | 唯一，不区分大小写由应用层保证';
COMMENT ON COLUMN user_account.password_hash IS '口令散列 | BCrypt；种子为哨兵 CHANGE_ME，local 启动时重算';
COMMENT ON COLUMN user_account.is_active IS '是否启用 | 停用后不可登录';
COMMENT ON COLUMN user_account.failed_attempts IS '连续失败次数 | 达到上限后锁定账号';
COMMENT ON COLUMN user_account.locked_until IS '锁定至 | 空表示未锁定';
COMMENT ON COLUMN user_account.last_login_at IS '最后登录时间 | 登录成功时更新';
COMMENT ON COLUMN user_account.must_change_pwd IS '强制改密 | 重置口令后置位';
COMMENT ON COLUMN user_account.created_at IS '审计：创建时间';
COMMENT ON COLUMN user_account.created_by IS '审计：创建人（员工ID）';
COMMENT ON COLUMN user_account.updated_at IS '审计：最后修改时间';
COMMENT ON COLUMN user_account.updated_by IS '审计：最后修改人（员工ID）';
COMMENT ON COLUMN user_account.is_deleted IS '审计：软删除标记';

CREATE INDEX idx_user_account_employee ON user_account (employee_id) WHERE is_deleted = false;

-- 刷新令牌白名单：JWT 本身无状态，此处只登记已签发的 jti 以便吊销。
CREATE TABLE refresh_token (
    token_id      bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    jti           varchar(64) NOT NULL,
    employee_id   varchar(32) NOT NULL,
    issued_at     timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    revoked_at    timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now(),
    created_by    varchar(32),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    updated_by    varchar(32),
    is_deleted    boolean     NOT NULL DEFAULT false,
    CONSTRAINT pk_refresh_token PRIMARY KEY (token_id),
    CONSTRAINT uq_refresh_token_jti UNIQUE (jti)
);
COMMENT ON TABLE refresh_token IS '刷新令牌 | 已签发刷新令牌的白名单，登出或改密时可即时吊销';
COMMENT ON COLUMN refresh_token.token_id IS '记录ID | 自增 | PK';
COMMENT ON COLUMN refresh_token.jti IS '令牌唯一标识 | JWT 的 jti 声明 | UQ';
COMMENT ON COLUMN refresh_token.employee_id IS '员工ID | 令牌归属 | FK';
COMMENT ON COLUMN refresh_token.issued_at IS '签发时间';
COMMENT ON COLUMN refresh_token.expires_at IS '过期时间';
COMMENT ON COLUMN refresh_token.revoked_at IS '吊销时间 | 空表示仍然有效';
COMMENT ON COLUMN refresh_token.created_at IS '审计：创建时间';
COMMENT ON COLUMN refresh_token.created_by IS '审计：创建人（员工ID）';
COMMENT ON COLUMN refresh_token.updated_at IS '审计：最后修改时间';
COMMENT ON COLUMN refresh_token.updated_by IS '审计：最后修改人（员工ID）';
COMMENT ON COLUMN refresh_token.is_deleted IS '审计：软删除标记';

CREATE INDEX idx_refresh_token_employee ON refresh_token (employee_id) WHERE is_deleted = false;

ALTER TABLE user_account
    ADD CONSTRAINT fk_user_account_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id) ON DELETE RESTRICT;

ALTER TABLE refresh_token
    ADD CONSTRAINT fk_refresh_token_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id) ON DELETE CASCADE;

CREATE TRIGGER trg_user_account_updated_at BEFORE UPDATE ON user_account
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_refresh_token_updated_at BEFORE UPDATE ON refresh_token
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
