-- ===========================================================================
-- V7 8D 报告补充结构 + 人员补充字段（追加迁移）
-- ===========================================================================
-- 真实 8D 报告（XTE-0071 / C2501869）里有两块基线无法承载的内容：
--   1. D1 跨职能团队表（Function | Name | Job Title）——基线没有这张表
--   2. D2/D4 等章节的大段叙述文字与内嵌图片——基线靠子表拼装，装不下自由文本
-- 另外 employee 缺英文名与职务，D1 的 Job Title 与中英文切换都需要。
-- ===========================================================================

SET search_path TO qms, public;

ALTER TABLE employee ADD COLUMN name_en   varchar(128);
ALTER TABLE employee ADD COLUMN job_title varchar(128);
COMMENT ON COLUMN employee.name_en IS '英文姓名 | 供中英文切换与 D1 团队表';
COMMENT ON COLUMN employee.job_title IS '职务 | 如 Quality Engineer；D1 团队表 Job Title 列';

-- ---------------------------------------------------------------- D1 跨职能团队
CREATE TABLE report_team_member (
    team_member_id  bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    report_id       varchar(32)  NOT NULL,
    function_name   varchar(128) NOT NULL,
    employee_id     varchar(32),
    member_name     varchar(128),
    job_title       varchar(128),
    sort_order      integer      NOT NULL DEFAULT 0,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      varchar(32),
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      varchar(32),
    is_deleted      boolean      NOT NULL DEFAULT false,
    CONSTRAINT pk_report_team_member PRIMARY KEY (team_member_id)
);
COMMENT ON TABLE report_team_member IS '报告团队成员 | 8D 报告 D1 跨职能团队表（Function/Name/Job Title），随报告保存以便复现历史版本';
COMMENT ON COLUMN report_team_member.team_member_id IS '记录ID | 自增 | PK';
COMMENT ON COLUMN report_team_member.report_id IS '报告ID | 所属报告 | FK';
COMMENT ON COLUMN report_team_member.function_name IS '职能 | 如 Engineering / Quality / Manufacturing';
COMMENT ON COLUMN report_team_member.employee_id IS '员工ID | 可空；非系统人员可只填姓名 | FK';
COMMENT ON COLUMN report_team_member.member_name IS '姓名 | 快照，人员变动不影响历史报告';
COMMENT ON COLUMN report_team_member.job_title IS '职务 | 快照';
COMMENT ON COLUMN report_team_member.sort_order IS '排序号 | 报告中的显示顺序';
COMMENT ON COLUMN report_team_member.created_at IS '审计：创建时间';
COMMENT ON COLUMN report_team_member.created_by IS '审计：创建人（员工ID）';
COMMENT ON COLUMN report_team_member.updated_at IS '审计：最后修改时间';
COMMENT ON COLUMN report_team_member.updated_by IS '审计：最后修改人（员工ID）';
COMMENT ON COLUMN report_team_member.is_deleted IS '审计：软删除标记';

CREATE INDEX idx_report_team_member_report ON report_team_member (report_id) WHERE is_deleted = false;

-- ---------------------------------------------------------------- 报告自由文本章节
CREATE TABLE report_section (
    section_id    bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    report_id     varchar(32) NOT NULL,
    step_code     varchar(4)  NOT NULL,
    section_key   varchar(64) NOT NULL,
    content_text  text,
    content_json  jsonb,
    created_at    timestamptz NOT NULL DEFAULT now(),
    created_by    varchar(32),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    updated_by    varchar(32),
    is_deleted    boolean     NOT NULL DEFAULT false,
    CONSTRAINT pk_report_section PRIMARY KEY (section_id),
    CONSTRAINT uq_report_section UNIQUE (report_id, step_code, section_key)
);
COMMENT ON TABLE report_section IS '报告章节内容 | 8D 报告各步骤的自由文本/富文本段落（D2 问题描述、D4 叙述等）；jsonb 承载结构化富文本，content_text 承载纯文本便于检索';
COMMENT ON COLUMN report_section.section_id IS '记录ID | 自增 | PK';
COMMENT ON COLUMN report_section.report_id IS '报告ID | 所属报告 | FK';
COMMENT ON COLUMN report_section.step_code IS '步骤代码 | D1-D8';
COMMENT ON COLUMN report_section.section_key IS '章节键 | 同一步骤内的多个段落，如 problem_description / risk_assessment';
COMMENT ON COLUMN report_section.content_text IS '纯文本 | 用于全文检索与导出兜底';
COMMENT ON COLUMN report_section.content_json IS '富文本 | jsonb，保存格式化结构';
COMMENT ON COLUMN report_section.created_at IS '审计：创建时间';
COMMENT ON COLUMN report_section.created_by IS '审计：创建人（员工ID）';
COMMENT ON COLUMN report_section.updated_at IS '审计：最后修改时间';
COMMENT ON COLUMN report_section.updated_by IS '审计：最后修改人（员工ID）';
COMMENT ON COLUMN report_section.is_deleted IS '审计：软删除标记';

CREATE INDEX idx_report_section_report ON report_section (report_id, step_code) WHERE is_deleted = false;

-- ---------------------------------------------------------------- 外键
ALTER TABLE report_team_member
    ADD CONSTRAINT fk_report_team_member_report FOREIGN KEY (report_id) REFERENCES report_8d (report_id) ON DELETE CASCADE;
ALTER TABLE report_team_member
    ADD CONSTRAINT fk_report_team_member_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id) ON DELETE SET NULL;

ALTER TABLE report_section
    ADD CONSTRAINT fk_report_section_report FOREIGN KEY (report_id) REFERENCES report_8d (report_id) ON DELETE CASCADE;

-- ---------------------------------------------------------------- 触发器
CREATE TRIGGER trg_report_team_member_updated_at BEFORE UPDATE ON report_team_member
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_report_section_updated_at BEFORE UPDATE ON report_section
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
